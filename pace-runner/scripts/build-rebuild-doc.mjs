// Regenerates docs/REBUILD.md (every project file verbatim) and docs/MANIFEST.sha256.
// Usage: pnpm rebuild-doc
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const SKIP_DIRS = new Set(['node_modules', 'dist', '.git']);
const GENERATED = new Set(['docs/REBUILD.md', 'docs/MANIFEST.sha256']);
const SKIP_FILES = new Set(['.DS_Store']);
// binary assets (design reference screenshots) can't be embedded as text; they're listed separately
const BINARY = /\.(png|jpe?g|webp|gif)$/i;

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name);
    if (statSync(abs).isDirectory()) {
      // hidden dirs are tool state (.git, editor/agent caches), never project source
      if (!SKIP_DIRS.has(name) && !name.startsWith('.')) out.push(...walk(abs));
    } else if (!SKIP_FILES.has(name) && !BINARY.test(name)) {
      const rel = relative(ROOT, abs).split(sep).join('/');
      if (!GENERATED.has(rel)) out.push(rel);
    }
  }
  return out;
}

const LANG = { ts: 'ts', mjs: 'js', js: 'js', json: 'json', css: 'css', html: 'html', md: 'markdown', yaml: 'yaml' };
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

const files = walk(ROOT).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const entries = files.map((path) => {
  const buf = readFileSync(join(ROOT, path));
  const text = buf.toString('utf8');
  if (Buffer.from(text, 'utf8').compare(buf) !== 0) throw new Error(`${path} is not valid UTF-8 text`);
  if (!text.endsWith('\n') || text.endsWith('\n\n')) throw new Error(`${path} must end with exactly one newline`);
  const longestTicks = Math.max(0, ...(text.match(/`+/g) ?? []).map((m) => m.length));
  const fence = '`'.repeat(Math.max(3, longestTicks + 1));
  const ext = path.includes('.') ? path.split('.').pop() : '';
  return { path, text, bytes: buf.length, hash: sha256(buf), fence, lang: LANG[ext] ?? '' };
});

const manifest = entries.map((e) => `${e.hash}  ${e.path}`).join('\n') + '\n';
const treeHash = sha256(Buffer.from(manifest));
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

const doc = [
  '# Pace Runner — Verbatim Rebuild Source',
  '',
  '> Generated by `pnpm rebuild-doc` (`scripts/build-rebuild-doc.mjs`). Do not edit by hand.',
  '> **This file is self-contained.** It is the only input needed to rebuild the project. The full specification is embedded below as `docs/SPEC.md`; read it after creating the files.',
  '',
  '## Inputs (mandatory)',
  '',
  'Build **only** from this document. Do not look for the visual reference images or the reference websites: everything visual is already in the source below.',
  '',
  'Allowed external inputs are limited to:',
  '',
  '- the public npm registry, via `pnpm install --frozen-lockfile`;',
  '- Google Fonts, loaded at runtime;',
  '- the Node.js and pnpm toolchain.',
  '',
  'How to work:',
  '',
  '- Work in a **new, empty directory**.',
  '- If anything seems missing or unclear, **stop and report it** instead of guessing.',
  '- Matching checksums prove the result is identical.',
  '- Finish your report by stating that only this document was used.',
  '',
  `- Files: **${entries.length}** · Tree hash (sha256 of the manifest): \`${treeHash}\``,
  `- Toolchain: Node.js \`${pkg.engines?.node ?? '?'}\` (built with 25.5.0) · \`${pkg.packageManager}\``,
  '',
  '## Rebuild procedure',
  '',
  '0. Toolchain: Node.js 25.5.0 and pnpm 11.24.0 (`corepack enable && corepack prepare pnpm@11.24.0 --activate`).',
  '1. In a new, empty directory, create a folder `pace-runner/` and, for **every** file below, create it at the given path with the exact contents of its fenced block.',
  '   - The file content is every line between the opening fence line and the closing fence line, **followed by exactly one newline**.',
  '   - Fences are 3+ backticks plus a language tag; a file\'s fence is always longer than any backtick run inside it.',
  '   - Do not reformat, re-indent, translate, or reorder anything.',
  '2. Write the manifest block below to `docs/MANIFEST.sha256`, then run `shasum -a 256 -c docs/MANIFEST.sha256` — every line must say `OK`.',
  '3. `pnpm install --frozen-lockfile` must not modify `pnpm-lock.yaml`.',
  '4. `pnpm exec tsc --noEmit` must print nothing and exit 0.',
  '5. `pnpm test` → 21 tests passed (2 files).',
  '6. `pnpm build` succeeds. A Vite "chunk larger than 500 kB" warning is expected.',
  '7. `pnpm dev` and walk through the acceptance checklist in `docs/SPEC.md` §12.',
  '',
  '## Manifest (`docs/MANIFEST.sha256`)',
  '',
  '```text',
  manifest.trimEnd(),
  '```',
  '',
  '## Files',
  '',
  ...entries.flatMap((e) => [
    `### \`${e.path}\``,
    '',
    `${e.bytes} bytes · sha256 \`${e.hash}\``,
    '',
    `${e.fence}${e.lang}`,
    e.text.slice(0, -1),
    e.fence,
    '',
  ]),
].join('\n');

writeFileSync(join(ROOT, 'docs/MANIFEST.sha256'), manifest);
writeFileSync(join(ROOT, 'docs/REBUILD.md'), doc);
console.log(`docs/REBUILD.md: ${entries.length} files, tree ${treeHash.slice(0, 12)}…`);
